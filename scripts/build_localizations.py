"""Generate standard Android resources; adding a language does not change UI code."""
import hashlib,json,re
from pathlib import Path
from xml.sax.saxutils import escape
ROOT=Path(__file__).resolve().parents[1]
translations=json.loads((ROOT/'localization/tr.json').read_text(encoding='utf-8'))
locales={'en': {source: source for source in translations}}
for path in sorted((ROOT/'localization').glob('*.json')):
    locales[path.stem]=json.loads(path.read_text(encoding='utf-8'))
def key(text):return 'm'+hashlib.sha1(text.encode()).hexdigest()[:12]
def android(text):return escape(text.replace('\\','\\\\').replace("'","\\'").replace('"','\\"'))
for language, mapping in locales.items():
    directory=ROOT/'app/src/main/res'/('values' if language=='en' else 'values-'+language)
    directory.mkdir(parents=True,exist_ok=True)
    lines=['<resources>']
    for source,translated in translations.items():
        formatting='' if re.search(r'%\d+\$s',source) else ' formatted="false"'
        lines.append(f'    <string name="{key(source)}"{formatting}>{android(mapping.get(source,source))}</string>')
    lines.append('</resources>')
    (directory/'strings.xml').write_text('\n'.join(lines)+'\n',encoding='utf-8')
patterns=[]
for source in translations:
    if '%1$s' in source:
        pattern='^'+re.sub(r'%\d+\\\$s','(.+?)', re.escape(source))+'$'
        patterns.append({'source':source,'pattern':pattern})
(ROOT/'app/src/main/assets/localized-patterns.json').write_text(json.dumps(patterns,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
lines=['// Generated by scripts/build_localizations.py. Do not edit.', 'package org.eightbit.bite.ui',
       'import org.eightbit.bite.R','internal val translatedIds: Map<String,Int> = mapOf(']
for source in translations:
    literal=json.dumps(source,ensure_ascii=False).replace('$', '\\$')
    lines.append(f'    {literal} to R.string.{key(source)},')
lines.append(')')
(ROOT/'app/src/main/java/org/eightbit/bite/ui/TranslatedIds.kt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
locale_xml=['<locale-config xmlns:android="http://schemas.android.com/apk/res/android">']
for locale in locales:locale_xml.append(f'    <locale android:name="{locale}" />')
locale_xml.append('</locale-config>')
(ROOT/'app/src/main/res/xml/locales_config.xml').write_text('\n'.join(locale_xml)+'\n',encoding='utf-8')
print(f'{len(translations)} resources generated for {", ".join(locales)}')
